// ============================================================================
// DM Magic Item Creator — a card inside DM Mode. Create items with stats,
// rarity and a description; "Save draft" keeps it private, "Submit" publishes it:
//   • it appears in the Magic tab of YOUR inventory immediately, and
//   • a ready-to-upload js/data/custommagic.js is downloaded — once that file
//     is uploaded to the site's repo, every player gets the items.
// (A static site has no server, so that one upload is the "publish" step.)
// Self-contained: doesn't touch js/app.js.
// ============================================================================
(function(){
  const LS_OVR = 'dnd5e_dm_items_overrides_v1';   // {added:{id:item}, deleted:[id]}
  const LS_DRAFTS = 'dnd5e_dm_items_drafts_v1';   // [item]
  const RARITIES = ['Common','Uncommon','Rare','Very Rare','Legendary','Artifact'];
  const TYPES = { magic:'Wondrous / other item', weapon:'Weapon', armor:'Armor', shield:'Shield', consumable:'Potion / consumable' };

  const esc = s => String(s==null?'':s).replace(/[&<>"]/g, c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));
  const num = (v,d=0)=>{ const n = parseFloat(v); return isNaN(n)?d:n; };
  const $ = id => document.getElementById(id);
  function lsGet(k, def){ try { const v = JSON.parse(localStorage.getItem(k)); return v == null ? def : v; } catch(e){ return def; } }
  function lsSet(k, v){ try { localStorage.setItem(k, JSON.stringify(v)); } catch(e){} }

  function fileItems(){ return (typeof CUSTOM_MAGIC_ITEMS !== 'undefined' && Array.isArray(CUSTOM_MAGIC_ITEMS)) ? CUSTOM_MAGIC_ITEMS : []; }

  // Drop local overrides the uploaded file already contains.
  function reconcile(){
    const ovr = lsGet(LS_OVR, {added:{}, deleted:[]});
    const fi = fileItems();
    Object.keys(ovr.added||{}).forEach(id=>{
      const f = fi.find(x=>x.id===id);
      if(f && JSON.stringify(f) === JSON.stringify(ovr.added[id])) delete ovr.added[id];
    });
    ovr.deleted = (ovr.deleted||[]).filter(id => fi.some(x=>x.id===id));
    lsSet(LS_OVR, ovr);
    return ovr;
  }

  function merged(){
    const ovr = reconcile();
    const out = fileItems().filter(i=>!(ovr.deleted||[]).includes(i.id)).map(i=> ovr.added[i.id] || i);
    Object.keys(ovr.added||{}).forEach(id=>{ if(!out.some(x=>x.id===id)) out.push(ovr.added[id]); });
    return out;
  }
  window.getMergedCustomMagic = merged;

  function pendingCount(){
    const o = reconcile();
    return Object.keys(o.added||{}).length + (o.deleted||[]).length;
  }

  function downloadFile(){
    const body = `// Campaign magic items shared with every player.\n// Generated by the DM Mode "Magic Item Creator" — upload this file over js/data/custommagic.js.\nconst CUSTOM_MAGIC_ITEMS = ${JSON.stringify(merged(), null, 2)};\n`;
    try {
      const blob = new Blob([body], {type:'text/javascript'});
      const a = document.createElement('a');
      a.href = URL.createObjectURL(blob); a.download = 'custommagic.js';
      document.body.appendChild(a); a.click(); a.remove();
      setTimeout(()=>URL.revokeObjectURL(a.href), 2000);
    } catch(e){ if(typeof showToast === 'function') showToast('Could not start the download.', 'warn'); }
  }

  // ---------------- UI ----------------
  const css = document.createElement('style');
  css.textContent = `
    .ic-row{display:flex; align-items:center; gap:8px; background:#fffaf0; border:1px solid var(--line); border-radius:7px; padding:6px 9px; margin-bottom:5px; font-size:13px;}
    .ic-row .nm{flex:1 1 auto; font-weight:700;} .ic-row .rar{font-size:10.5px; color:var(--ink-soft); font-family:'JetBrains Mono',monospace;}
    .ic-row button{border:none; background:none; cursor:pointer; color:var(--ink-soft); font-size:12px;}
    .ic-banner{background:#fff1d0; border:1px solid var(--gold); border-radius:7px; padding:8px 10px; margin-bottom:10px; font-size:12.5px;}
    .ic-form{width:min(560px,94vw); max-height:92vh; overflow:auto;}
    .ic-grid{display:grid; grid-template-columns:1fr 1fr; gap:7px; margin-bottom:8px;}
    .ic-grid label{font-size:10.5px; display:flex; flex-direction:column; gap:2px; color:var(--ink-soft);}
    .ic-grid input, .ic-grid select{width:100%;} .ic-grid .full{grid-column:1 / -1;}
    .ic-grid .chk{flex-direction:row; align-items:center; gap:6px; font-size:12px; color:var(--ink);}
    .ic-sub{font-family:'Cinzel',serif; font-size:12px; font-weight:700; color:var(--burgundy); margin:8px 0 4px;}
  `;
  document.head.appendChild(css);

  function renderCard(){
    const card = $('icCard'); if(!card) return;
    const items = merged();
    const drafts = lsGet(LS_DRAFTS, []);
    const pend = pendingCount();
    let h = `<h2>✨ Magic Item Creator
      <button type="button" class="btn small" id="icNew" style="margin-left:auto; align-self:center;">+ New Item</button></h2>`;
    if(pend) h += `<div class="ic-banner">⚠ <b>${pend} change${pend>1?'s':''} not live for players yet.</b> Upload the downloaded <code>custommagic.js</code> to <code>js/data/</code> in your GitHub repo.
      <div style="margin-top:6px;"><button type="button" class="btn small" id="icDownload">⬇ Download custommagic.js</button></div></div>`;
    h += `<div class="ic-sub">Published items (${items.length})</div>`;
    h += items.length ? items.map(i=>`<div class="ic-row" data-id="${esc(i.id)}"><span class="nm">${esc(i.name)}</span><span class="rar">${esc(i.rarity||'')} · ${esc(TYPES[typeKey(i)]||'')}</span>
        <button data-act="edit" title="Edit">✎</button><button data-act="del" title="Delete">🗑</button></div>`).join('')
      : '<div style="font-size:12px; color:var(--ink-soft);">No campaign items yet.</div>';
    if(drafts.length){
      h += `<div class="ic-sub">Drafts (${drafts.length}) — private</div>` + drafts.map(i=>`<div class="ic-row" data-id="${esc(i.id)}" data-draft="1"><span class="nm">${esc(i.name||'(unnamed)')}</span><span class="rar">${esc(i.rarity||'')}</span>
        <button data-act="edit" title="Edit">✎</button><button data-act="del" title="Delete">🗑</button></div>`).join('');
    }
    card.innerHTML = h;
    const nb = $('icNew'); if(nb) nb.addEventListener('click', ()=> openForm(null));
    const db = $('icDownload'); if(db) db.addEventListener('click', downloadFile);
    card.querySelectorAll('.ic-row button').forEach(b=> b.addEventListener('click', ()=>{
      const row = b.closest('.ic-row'); const id = row.dataset.id; const isDraft = !!row.dataset.draft;
      if(b.dataset.act === 'edit'){
        const it = isDraft ? lsGet(LS_DRAFTS, []).find(x=>x.id===id) : merged().find(x=>x.id===id);
        if(it) openForm(it, isDraft);
      } else {
        if(!confirm('Delete this item?')) return;
        if(isDraft) lsSet(LS_DRAFTS, lsGet(LS_DRAFTS, []).filter(x=>x.id!==id));
        else removePublished(id);
        renderCard();
      }
    }));
  }

  function typeKey(i){ return i.cat === 'armor' ? (i.armorType === 'Shield' ? 'shield' : 'armor') : (i.cat || 'magic'); }

  function removePublished(id){
    const ovr = lsGet(LS_OVR, {added:{}, deleted:[]});
    delete ovr.added[id];
    if(fileItems().some(x=>x.id===id) && !ovr.deleted.includes(id)) ovr.deleted.push(id);
    lsSet(LS_OVR, ovr);
  }

  function closeForm(){ const o = $('icFormOverlay'); if(o) o.remove(); }

  function openForm(item, isDraft){
    closeForm();
    const it = item ? JSON.parse(JSON.stringify(item)) : { id:`cm_${Date.now()}`, cat:'magic', rarity:'Uncommon', weight:0, desc:'' };
    const o = document.createElement('div');
    o.id = 'icFormOverlay'; o.className = 'spell-modal-overlay'; o.style.zIndex = 340;
    o.innerHTML = `<div class="spell-modal-box ic-form">
      <button type="button" class="spell-modal-close" id="icClose" aria-label="Close">✕</button>
      <h3>${item ? 'Edit' : 'New'} magic item</h3>
      <div class="ic-grid">
        <label class="full">Name<input class="plain-input" id="icName"></label>
        <label>Type<select class="plain-input" id="icType">${Object.entries(TYPES).map(([k,v])=>`<option value="${k}">${v}</option>`).join('')}</select></label>
        <label>Rarity<select class="plain-input" id="icRarity">${RARITIES.map(r=>`<option>${r}</option>`).join('')}</select></label>
        <label>Weight (lb)<input class="plain-input" id="icWeight" type="number" step="0.25" min="0"></label>
        <label>Value<input class="plain-input" id="icValue" placeholder="e.g. 500 gp"></label>
        <label class="chk"><input type="checkbox" id="icAttune"> Requires attunement</label>
        <label>Max charges (0 = none)<input class="plain-input" id="icCharges" type="number" min="0"></label>
      </div>
      <div id="icWeaponBox" class="ic-grid">
        <div class="ic-sub full">Weapon stats</div>
        <label>Damage dice<input class="plain-input" id="icDmg" placeholder="1d8"></label>
        <label>Damage type<input class="plain-input" id="icDmgType" placeholder="slashing"></label>
        <label>Properties<input class="plain-input" id="icProps" placeholder="Versatile (1d10)"></label>
        <label>Magic bonus (+N)<input class="plain-input" id="icBonus" type="number"></label>
        <label class="chk"><input type="checkbox" id="icRanged"> Ranged weapon</label>
      </div>
      <div id="icArmorBox" class="ic-grid">
        <div class="ic-sub full">Armor / shield stats</div>
        <label>Armor type<select class="plain-input" id="icArmorType"><option>Light</option><option>Medium</option><option>Heavy</option></select></label>
        <label>Base AC (shield: bonus)<input class="plain-input" id="icAc" type="number"></label>
        <label>Magic AC bonus<input class="plain-input" id="icAcBonus" type="number"></label>
        <label>Dex cap<select class="plain-input" id="icDexCap"><option value="99">Full Dex</option><option value="2">Max +2</option><option value="-1">No Dex</option></select></label>
        <label>Str required<input class="plain-input" id="icStr" type="number"></label>
        <label class="chk"><input type="checkbox" id="icStealth"> Stealth disadvantage</label>
      </div>
      <label style="font-size:10.5px; color:var(--ink-soft);">Description / abilities</label>
      <textarea id="icDesc" rows="6" style="width:100%; margin-bottom:10px;" placeholder="What does it do? Activation, charges, curses, lore…"></textarea>
      <div style="display:flex; gap:8px; justify-content:flex-end; flex-wrap:wrap;">
        <button type="button" class="btn small secondary" id="icDraft">💾 Save draft</button>
        <button type="button" class="btn small" id="icSubmit">✅ Submit</button>
      </div></div>`;
    document.body.appendChild(o);
    o.addEventListener('click', e=>{ if(e.target === o) closeForm(); });
    $('icClose').addEventListener('click', closeForm);

    // fill
    $('icName').value = it.name || '';
    $('icType').value = typeKey(it);
    $('icRarity').value = it.rarity || 'Uncommon';
    $('icWeight').value = it.weight ?? 0;
    $('icValue').value = it.value || '';
    $('icAttune').checked = !!it.attune;
    $('icCharges').value = it.chargesMax || 0;
    $('icDmg').value = it.dmg || ''; $('icDmgType').value = it.dmgType || ''; $('icProps').value = it.props || '';
    $('icBonus').value = it.bonus || 0; $('icRanged').checked = !!it.ranged;
    $('icArmorType').value = (it.armorType && it.armorType !== 'Shield') ? it.armorType : 'Light';
    $('icAc').value = it.ac ?? 11; $('icAcBonus').value = it.acBonus || 0;
    $('icDexCap').value = String(it.dexCap ?? 99); $('icStr').value = it.strReq || 0; $('icStealth').checked = !!it.stealthDis;
    $('icDesc').value = it.desc || '';

    const toggle = ()=>{
      const t = $('icType').value;
      $('icWeaponBox').style.display = t === 'weapon' ? '' : 'none';
      $('icArmorBox').style.display = (t === 'armor' || t === 'shield') ? '' : 'none';
      $('icArmorType').parentElement.style.display = t === 'shield' ? 'none' : '';
      $('icDexCap').parentElement.style.display = t === 'shield' ? 'none' : '';
      $('icStr').parentElement.style.display = t === 'shield' ? 'none' : '';
    };
    $('icType').addEventListener('change', ()=>{
      if($('icType').value === 'shield' && num($('icAc').value) > 3) $('icAc').value = 2;
      if($('icType').value === 'armor' && num($('icAc').value) < 5) $('icAc').value = 11;
      toggle();
    });
    toggle();

    function collect(){
      const t = $('icType').value;
      const out = { id: it.id, name: $('icName').value.trim(), cat: (t === 'shield' ? 'armor' : t), rarity: $('icRarity').value,
        attune: $('icAttune').checked, weight: num($('icWeight').value), value: $('icValue').value.trim(), desc: $('icDesc').value };
      const cm = Math.max(0, Math.round(num($('icCharges').value)));
      if(cm){ out.chargesMax = cm; out.charges = cm; }
      if(t === 'weapon') Object.assign(out, { dmg:$('icDmg').value.trim(), dmgType:$('icDmgType').value.trim(), props:$('icProps').value.trim(), bonus:num($('icBonus').value), ranged:$('icRanged').checked, prof:true });
      if(t === 'armor') Object.assign(out, { armorType:$('icArmorType').value, ac:num($('icAc').value,11), acBonus:num($('icAcBonus').value), dexCap:num($('icDexCap').value,99), strReq:num($('icStr').value), stealthDis:$('icStealth').checked });
      if(t === 'shield') Object.assign(out, { armorType:'Shield', ac:num($('icAc').value,2), acBonus:num($('icAcBonus').value), dexCap:0, strReq:0, stealthDis:false });
      return out;
    }

    $('icDraft').addEventListener('click', ()=>{
      const d = collect();
      const drafts = lsGet(LS_DRAFTS, []).filter(x=>x.id!==d.id); drafts.push(d); lsSet(LS_DRAFTS, drafts);
      closeForm(); renderCard();
      if(typeof showToast === 'function') showToast('Draft saved (private).');
    });
    $('icSubmit').addEventListener('click', ()=>{
      const d = collect();
      if(!d.name){ if(typeof showToast === 'function') showToast('Give the item a name first.', 'warn'); return; }
      const ovr = lsGet(LS_OVR, {added:{}, deleted:[]});
      ovr.added[d.id] = d;
      ovr.deleted = (ovr.deleted||[]).filter(x=>x!==d.id);
      lsSet(LS_OVR, ovr);
      lsSet(LS_DRAFTS, lsGet(LS_DRAFTS, []).filter(x=>x.id!==d.id));
      closeForm(); renderCard();
      downloadFile();
      if(typeof showToast === 'function') showToast(`${d.name} submitted — upload the downloaded custommagic.js to publish it to all players.`, 'warn');
    });
  }

  function init(){
    const grid = document.querySelector('.dm-mode-grid');
    if(!grid) return;
    const card = document.createElement('div');
    card.className = 'card'; card.id = 'icCard';
    grid.appendChild(card);
    renderCard();
  }
  if(document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
